import { readdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const wordsDirectory = resolve(import.meta.dirname, "../words");

async function buildRoleBank(role) {
  const suffix = `.${role}.js`;
  const files = (await readdir(wordsDirectory)).filter((file) => file.endsWith(suffix)).sort();
  const entries = [];
  for (const file of files) {
    const source = await readFile(resolve(wordsDirectory, file), "utf8");
    const match = source.match(/export default (\{[\s\S]*\});\s*$/);
    if (!match) throw new Error(`Could not read the default export in ${file}`);
    const id = file.slice(0, -suffix.length);
    entries.push(`  ${JSON.stringify(id)}: ${match[1]}`);
  }
  const output = `// Generated by npm run generate:word-banks. Do not edit by hand.\nexport default {\n${entries.join(",\n")}\n};\n`;
  await writeFile(resolve(wordsDirectory, `role-${role}.js`), output);
}

await Promise.all([buildRoleBank("a"), buildRoleBank("b")]);
